// The DeepSeek account sign-in button (dsh 0.2.1+) completes an OAuth PKCE flow
// whose callback origin must be loopback HTTP — `dsh loginOrigin()` accepts only
// `http://localhost|127.0.0.1|[::1]:<port>`. A hub served on a LAN hostname can
// never satisfy that, so the button is dead weight there. Instead of patching
// dsh (and defeating that deliberate guard), the hub passes a `--patch` overlay
// to the instances IT spawns that disables the account-UI plugin. The user's own
// `$DSH_HOME/cordis.patch.yml` is untouched, so a manually launched dsh keeps
// the button; a grant obtained there is shared back through DSH_HOME.
import fs from 'node:fs';
import path from 'node:path';

import { RUNTIME_DIR } from './config.mjs';

/** Overlay file handed to spawned dsh instances via `--patch`. */
export const ACCOUNT_UI_PATCH_PATH = path.join(RUNTIME_DIR, 'hub-no-account-ui.patch.yml');

const CONTENT = `# Generated by dsh-hub. Disables the DeepSeek account sign-in UI in this
# hub-spawned instance. The flow only accepts a loopback browser origin, which a
# LAN-served hub is not; see dsh-hub's README ("DeepSeek account sign-in").
- id: ui-settings-account
  disabled: true
`;

/**
 * Write the overlay so spawned instances (running as their own user) can read
 * it. The file is not secret; 0644 makes it readable across the uid boundary.
 * @returns true when the overlay is in place.
 */
export function writeAccountUiPatch() {
  try {
    fs.writeFileSync(ACCOUNT_UI_PATCH_PATH, CONTENT, { mode: 0o644 });
    fs.chmodSync(ACCOUNT_UI_PATCH_PATH, 0o644);
    return true;
  } catch (err) {
    console.error(`[hub] could not write ${ACCOUNT_UI_PATCH_PATH}:`, err.message);
    return false;
  }
}
