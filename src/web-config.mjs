// Admin-maintained global dsh overlays for instances the hub spawns.
//
// `/etc/dsh-hub/web_config.d/*.yml` (or HUB_WEB_CONFIG_DIR) are applied in file
// name order as dsh `--patch` layers. They are world-readable and are passed to
// every user's dsh process, so they must never hold secrets — per-user secrets
// belong in that user's `~/.dsh/cordis.patch.yml` (0600).
//
// The hub's own default (hide the DeepSeek account UI, whose PKCE login only
// accepts a loopback browser origin) is generated into a world-readable runtime
// directory and applied before the admin drop-ins, so a drop-in can restore a
// row with `disabled: false`.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { CFG, RUNTIME_DIR } from './config.mjs';

const BUILTIN_NAME = '00-dsh-hub-account-ui.patch.yml';

const BUILTIN_CONTENT = `# Generated by dsh-hub. Disables the DeepSeek account sign-in UI in this
# hub-spawned instance. Its OAuth PKCE flow accepts a loopback browser origin
# only, which a LAN-served hub is not. Override from a later web_config.d
# drop-in with "- id: ui-settings-account" / "  disabled: false".
- id: ui-settings-account
  disabled: true
`;

let builtinPath = null;
let warnedInsecureDir = false;

/** A world-readable directory for the generated overlay. */
function builtinDir() {
  for (const dir of ['/run/dsh-hub', path.join(os.tmpdir(), 'dsh-hub-runtime')]) {
    try {
      fs.mkdirSync(dir, { recursive: true, mode: 0o755 });
      fs.chmodSync(dir, 0o755);
      return dir;
    } catch { /* try the next candidate */ }
  }
  return RUNTIME_DIR;
}

/**
 * Write the hub's built-in overlay (the account-UI default).
 * @returns its path, or null when hiding is disabled or the write failed.
 */
export function writeBuiltinPatch() {
  builtinPath = null;
  if (!CFG.hideAccountUi) return null;
  const file = path.join(builtinDir(), BUILTIN_NAME);
  try {
    fs.writeFileSync(file, BUILTIN_CONTENT, { mode: 0o644 });
    fs.chmodSync(file, 0o644);
    builtinPath = file;
    return file;
  } catch (err) {
    console.error(`[hub] could not write ${file}:`, err.message);
    return null;
  }
}

function warnIfInsecureDir() {
  if (warnedInsecureDir) return;
  warnedInsecureDir = true;
  try {
    if (fs.statSync(CFG.webConfigDir).mode & 0o022) {
      console.warn(`[hub] web config: ${CFG.webConfigDir} is group/other-writable; only root should own it`);
    }
  } catch { /* a missing directory is allowed */ }
}

/**
 * The `--patch` arguments for one spawn: the built-in overlay, then the admin
 * drop-ins in file-name order. Files the spawned user could not read are
 * skipped with a warning, because dsh would fail to boot on them.
 * @returns absolute patch paths, in application order.
 */
export function webConfigPatches() {
  const patches = builtinPath ? [builtinPath] : [];
  let entries;
  try {
    entries = fs.readdirSync(CFG.webConfigDir, { withFileTypes: true });
  } catch (err) {
    if (err.code !== 'ENOENT') console.warn(`[hub] web config: ${CFG.webConfigDir}: ${err.message}`);
    return patches;
  }
  warnIfInsecureDir();
  const names = entries
    .filter((entry) => !entry.name.startsWith('.') && /\.ya?ml$/i.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  for (const name of names) {
    const file = path.join(CFG.webConfigDir, name);
    let stat;
    try {
      stat = fs.statSync(file);
    } catch {
      continue;
    }
    if (!stat.isFile()) continue;
    if ((stat.mode & 0o004) === 0) {
      console.warn(`[hub] web config: skipping ${file}: not world-readable for the spawned user`);
      continue;
    }
    patches.push(file);
  }
  return patches;
}
